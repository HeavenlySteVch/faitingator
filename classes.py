def class_by_spec(spec_id: int | None) -> tuple[str, str]:
    """Возвращает (класс, специализация) по specID."""
    if not spec_id:
        return "", ""
    return SPECS.get(int(spec_id), ("", ""))


def refine_spec(cls: str, spec_id: int, spell_ids: dict[int, int]) -> int:
    """Уточняет специализацию по способностям (в логе может быть лут-спек).

    Возвращает specID: если по способностям видно другую специализацию того же
    класса — её, иначе исходную.
    """
    table = SPEC_SPELLS.get(cls)
    if not table or not spell_ids:
        return spec_id
    scores = {sid: sum(spell_ids.get(i, 0) for i in ids) for sid, ids in table.items()}
    best = max(scores, key=lambda s: scores[s])
    if scores[best] < 3:  # слишком мало данных, чтобы спорить с логом
        return spec_id
    if scores.get(int(spec_id or 0), 0) >= scores[best]:
        return spec_id
    return best


def guess_class(spell_ids: dict[int, int]) -> str:
    """Определяет класс по частоте классовых способностей (spell_id -> число кастов)."""
    if not spell_ids:
        return ""
    scores: dict[str, int] = {}
    for sid, count in spell_ids.items():
        cls = SPELL_CLASS.get(sid)
        if cls:
            scores[cls] = scores.get(cls, 0) + count
    if not scores:
        return ""
    ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
    best, best_score = ranked[0]
    second = ranked[1][1] if len(ranked) > 1 else 0
    # требуем уверенности: минимум 3 попадания и заметный отрыв
    if best_score >= 3 and best_score >= second * 2:
        return best
    return ""


