def dungeon_timer(zone: str) -> int | None:
    """Таймер подземелья по названию зоны (секунды) или None."""
    if not zone:
        return None
    low = zone.lower().replace("ё", "е")
    for name, seconds in DUNGEON_TIMERS.items():
        if name in low:
            return seconds
    return None
